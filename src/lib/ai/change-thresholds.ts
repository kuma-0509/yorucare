import type { MoodScore } from "../types";

/**
 * 変化の提示に使う閾値の置き場所。
 *
 * 閾値をコードのあちこちに散らすと、「どこからが低いのか」を
 * アプリが暗黙に決めていることが読めなくなる。
 * 変えるときも1か所で足りるよう、この1ファイルへ集約する。
 *
 * ここにあるのは「どの事実を数えるか」の区切りであって、
 * 危険度や緊急度の基準ではない。閾値を超えた／超えないで
 * 表示の強さを変えたり、警告を出したりしてはいけない。
 */
export const CHANGE_THRESHOLDS = {
  /** 何日分を対象にするか。記録の入力範囲と揃える */
  periodDays: 7,

  /**
   * 「気分が『少ししんどい』以下だった日」として数える上限。
   * 2 =「少ししんどい」。この値そのものは良し悪しを意味しない。
   */
  lowMoodAtMost: 2 as MoodScore,

  /**
   * 「睡眠時間が短かった日」として数える上限（分）。
   * 360分 = 6時間。医学的な基準ではなく、本人が読みやすい区切りとして置く。
   */
  shortSleepMinutesAtMost: 360,

  /** しんどさのサインとして数える段階 */
  countedWarningLevels: ["yes"] as const,

  /** 服薬について「忘れた」と数える段階 */
  countedMedicationStatuses: ["forgot"] as const,

  /** 上位に出すしんどさのサインの件数 */
  topWarningTagCount: 1,

  /**
   * 事実を1件出すために最低限必要な母数。
   * 1日分を「期間の傾向」として読ませないため、
   * この値を下回る項目は表示しない（0ではなく null として扱う）。
   */
  minDenominator: 1,
} as const;
